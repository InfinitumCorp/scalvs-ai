// public/mixpanel-boot.js as served to browsers, generated from environment variables by
// scripts/build-assets.mjs (dist/) and dev-server.mjs. The Mixpanel project token is public
// (it ships to every browser), but it still lives in the environment, not in git.
//
//   MIXPANEL_PROJECT_TOKEN   32-hex project token (Mixpanel > Project settings). Unset: Mixpanel stays off.
//   MIXPANEL_REGION          US (default), EU or IN: must match the project's data residency.
//   MIXPANEL=off             turns it off even when a token is set.
//
// The vendored SDK (public/mixpanel.vendor.js, mixpanel-browser 2.85.0 core build, Apache-2.0)
// records one page view per load (domain + path) and sessions. No autocapture, replay, IP geolocation or UTM capture.

export function mixpanelBoot(env = process.env) {
  const token = String(env.MIXPANEL_PROJECT_TOKEN ?? '').trim();
  const region = ['US', 'EU', 'IN'].includes(String(env.MIXPANEL_REGION ?? '').toUpperCase()) ? String(env.MIXPANEL_REGION).toUpperCase() : 'US';
  const on = /^[0-9a-f]{32}$/i.test(token) && String(env.MIXPANEL ?? '').toLowerCase() !== 'off';
  const head = '/* Generated by scripts/mixpanel-boot.mjs. Public Mixpanel project token; privacy-first options in mixpanel.vendor.js. */\n';
  if (!on) return `${head}/* Mixpanel is off: MIXPANEL_PROJECT_TOKEN is not set (or MIXPANEL=off). */\n`;
  return `${head}if (typeof initInfinitumMixpanel === "function") {\n  initInfinitumMixpanel(${JSON.stringify(token)}, { region: ${JSON.stringify(region)}, product: "scalvs" });\n}\n`;
}
